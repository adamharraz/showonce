/* Isolated fixture: synthetic camera, test-only Live reply and a triangle GLB.
   Verifies transport/rendering, never physical SF3D generation accuracy. */
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/Adam Harraz/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('fs');let browser;let stage='start';
(async()=>{
  fs.mkdirSync('artifacts/ui',{recursive:true});
  browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']});
  const context=await browser.newContext({viewport:{width:1440,height:1000},permissions:['camera','microphone']});
  const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8002/coach');await page.getByRole('button',{name:/Enter as instructor/}).click();
  await page.getByRole('heading',{name:'Learn with someone beside you.'}).waitFor();
  await page.getByPlaceholder('For example, assembling a breadboard circuit').fill('Synthetic UI transport check');
  await page.getByRole('checkbox',{name:/Everyone captured is 18.*Google/}).check();
  await page.getByRole('button',{name:'Start live coaching',exact:true}).click();
  await page.locator('.coach-live-pill.on').waitFor();
  await page.waitForFunction(()=>document.querySelector('.coach-camera-footer')?.textContent.match(/[1-9]\d* frames shared/));
  stage='photo capture';await page.getByRole('button',{name:'Capture build photo',exact:true}).click();
  await page.getByAltText('Photo selected for 3D generation').waitFor();
  await page.getByRole('textbox',{name:'Model title',exact:true}).fill('Synthetic GLB fixture');
  const generate=page.getByRole('button',{name:'Generate 3D model',exact:true});
  if(await generate.isEnabled())throw new Error('Photo processing consent is not enforced');
  await page.getByRole('checkbox',{name:/Everyone captured is 18.*Modal/}).check();
  await generate.click();stage='GLB viewer';
  await page.getByText('Generated from your photo',{exact:true}).waitFor();
  await page.getByRole('img',{name:'Generated 3D model of your captured build'}).waitFor();
  await page.getByText('Loading your generated model…',{exact:true}).waitFor({state:'hidden'});
  const downloaded=page.waitForEvent('download');await page.getByRole('button',{name:'Download GLB',exact:true}).click();
  const file=await downloaded;if(!file.suggestedFilename().endsWith('.glb'))throw new Error('Model download is not a GLB');
  await page.screenshot({path:'artifacts/ui/photo-to-3d-fixture-desktop.png',fullPage:true});
  stage='Live response';await page.getByRole('button',{name:'Look at this now',exact:true}).click();
  await page.getByText('Test-only live reply.',{exact:true}).waitFor();
  const frameText=await page.locator('.coach-camera-footer').innerText();
  await page.getByRole('button',{name:'Pause sharing',exact:true}).click();await page.getByRole('button',{name:'Resume',exact:true}).waitFor();
  await page.waitForTimeout(2700);
  const paused=await page.locator('.coach-camera-footer').innerText();
  if(frameText.match(/(\d+) frames/)[1]!==paused.match(/(\d+) frames/)[1])throw new Error('Camera frames continued during pause');
  await page.getByRole('button',{name:'Resume',exact:true}).click();await page.locator('.coach-live-pill.on').waitFor();
  await page.getByRole('textbox',{name:'Message the live assistant'}).fill('A second synthetic question');
  await page.getByRole('button',{name:'Send message',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.coach-message.assistant').length===2);
  await page.getByRole('button',{name:'Finish',exact:true}).click();
  await page.getByRole('button',{name:'Start a new session',exact:true}).waitFor();
  stage='mobile';await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right<=1);
  await page.screenshot({path:'artifacts/ui/photo-to-3d-fixture-mobile.png',fullPage:true,animations:'disabled'});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw new Error('Mobile layout overflows horizontally');
  stage='saved model';await page.reload();await page.getByText('Saved 3D models and jobs',{exact:true}).click();
  await page.getByRole('button',{name:/Synthetic GLB fixture · ready/}).first().click();
  await page.getByText('Generated from your photo',{exact:true}).waitFor();
  if(errors.length)throw new Error(errors.join('\n'));
  fs.writeFileSync('artifacts/ui/photo-to-3d-fixture-report.json',JSON.stringify({passed:true,synthetic_camera:true,test_only_model:true,test_only_glb:true,checks:['camera capture','photo processing consent','async job','private GLB fetch','GLB renderer','download','saved model reload','live audio pacing','chat','pause/resume','finish','desktop/mobile'],errors},null,2));
  console.log('Photo-to-3D and Live Coach browser checks passed with isolated synthetic fixtures.');
})().catch(e=>{console.error(stage,e.stack);process.exitCode=1;}).finally(async()=>{await browser?.close();});
