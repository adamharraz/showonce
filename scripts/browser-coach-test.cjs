/* Local Live Coach UI regression with synthetic camera and test-only model output. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "C:/Users/Adam Harraz/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright");
const fs = require("fs");
let browser;
(async () => {
  fs.mkdirSync("artifacts/ui", { recursive: true });
  browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || "C:/Program Files/Google/Chrome/Application/chrome.exe", args: ["--use-fake-device-for-media-stream", "--use-fake-ui-for-media-stream"] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ["camera", "microphone"] });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await page.goto("http://127.0.0.1:8002/coach");
  await page.getByRole("button", { name: /Enter as instructor/ }).click();
  await page.getByRole("heading", { name: "Learn with someone beside you." }).waitFor();
  await page.getByPlaceholder("For example, assembling a breadboard circuit").fill("Synthetic UI transport check");
  await page.getByRole("checkbox", { name: /Everyone captured is 18/ }).check();
  await page.getByRole("button", { name: "Start live coaching", exact: true }).click();
  await page.locator(".coach-live-pill.on").waitFor();
  await page.waitForFunction(() => document.querySelector(".coach-camera-footer")?.textContent.match(/[1-9]\d* frames shared/));
  await page.getByRole("button", { name: "Look at this now" }).click();
  await page.getByText("Test-only live reply.", { exact: true }).waitFor();
  await page.screenshot({ path: "artifacts/ui/live-coach-desktop-fixture.png", fullPage: true });
  const frameText = await page.locator(".coach-camera-footer").innerText();
  await page.getByRole("button", { name: "Pause sharing", exact: true }).click();
  await page.getByRole("button", { name: "Resume", exact: true }).waitFor();
  await page.waitForTimeout(2700);
  const pausedFrameText = await page.locator(".coach-camera-footer").innerText();
  if (frameText.match(/(\d+) frames/)[1] !== pausedFrameText.match(/(\d+) frames/)[1]) throw new Error("Frames continued during pause");
  await page.getByRole("button", { name: "Resume", exact: true }).click();
  await page.locator(".coach-live-pill.on").waitFor();
  await page.getByRole("textbox", { name: "Message the live assistant" }).fill("A second synthetic question");
  await page.getByRole("button", { name: "Send message", exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll(".coach-message.assistant").length === 2);
  await page.getByRole("button", { name: "Finish", exact: true }).click();
  await page.getByRole("button", { name: "Start a new session", exact: true }).waitFor();
  await page.getByText("Recent conversations", { exact: true }).click();
  await page.getByRole("button", { name: /Synthetic UI transport check/ }).first().waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector(".sidebar").getBoundingClientRect().right <= 1);
  await page.screenshot({ path: "artifacts/ui/live-coach-mobile-fixture.png", fullPage: true, animations: "disabled" });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
  if (overflow) throw new Error("Mobile layout overflows horizontally");
  if (errors.length) throw new Error(errors.join("\n"));
  fs.writeFileSync("artifacts/ui/live-coach-fixture-report.json", JSON.stringify({ passed: true, synthetic_camera: true, test_only_model: true, checks: ["native PCM transport", "camera frames", "chat", "pause stops sharing", "resume", "finish", "saved history", "desktop/mobile layout"], errors }, null, 2));
  console.log("Live Coach browser checks passed with synthetic camera and a test-only model.");
})().catch((e) => { console.error(e.message); process.exitCode = 1; }).finally(async () => { await browser?.close(); });
